create table if not exists public.students (
  student_id text primary key,
  password_hash text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.typing_records (
  id bigint generated by default as identity primary key,
  student_id text not null references public.students(student_id) on delete cascade,
  korean_score integer not null check (korean_score >= 0),
  english_score integer not null check (english_score >= 0),
  recorded_at date not null default current_date,
  created_at timestamptz not null default now()
);

create index if not exists typing_records_student_date_idx
  on public.typing_records (student_id, recorded_at);
