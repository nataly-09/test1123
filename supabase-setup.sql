-- 타자 기록 사이트용 Supabase 테이블 설정

create table if not exists public.students (
  student_id text primary key
    check (student_id ~ '^[0-9]{4}$'),
  password_hash text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.typing_records (
  id bigint generated by default as identity primary key,
  student_id text not null
    references public.students(student_id) on delete cascade,
  korean_score integer not null
    check (korean_score between 0 and 9999),
  english_score integer not null
    check (english_score between 0 and 9999),
  recorded_at date not null default current_date,
  created_at timestamptz not null default now()
);

create unique index if not exists typing_records_student_date_unique
  on public.typing_records (student_id, recorded_at);

alter table public.students enable row level security;
alter table public.typing_records enable row level security;

-- 데모용 공개 정책입니다.
-- 실제 운영에서는 Edge Functions 또는 Supabase Auth로 보호하세요.
drop policy if exists "demo_students_select" on public.students;
create policy "demo_students_select"
  on public.students for select to anon using (true);

drop policy if exists "demo_students_insert" on public.students;
create policy "demo_students_insert"
  on public.students for insert to anon with check (true);

drop policy if exists "demo_records_select" on public.typing_records;
create policy "demo_records_select"
  on public.typing_records for select to anon using (true);

drop policy if exists "demo_records_insert" on public.typing_records;
create policy "demo_records_insert"
  on public.typing_records for insert to anon with check (true);

drop policy if exists "demo_records_update" on public.typing_records;
create policy "demo_records_update"
  on public.typing_records for update to anon
  using (true) with check (true);

grant usage on schema public to anon;
grant select, insert on public.students to anon;
grant select, insert, update on public.typing_records to anon;
grant usage, select on sequence public.typing_records_id_seq to anon;
